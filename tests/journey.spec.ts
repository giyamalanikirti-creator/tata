import {test,expect} from '@playwright/test';
test('complete farmer, verifier and lender journey persists and revokes access',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Dhara passport',exact:true}).click();
 await page.getByRole('button',{name:'Revoke sharing'}).click();
 await page.getByRole('button',{name:'Revoke access'}).click();
 await page.getByRole('button',{name:'Improvement planner',exact:true}).click();
 await page.locator('.planner-card').filter({has:page.getByRole('heading',{name:'Rainwater harvesting',exact:true})}).getByRole('button',{name:'Add to my plan'}).click();
 await page.getByRole('button',{name:'Submit evidence',exact:true}).click();
 await page.getByLabel('Improvement',{exact:true}).selectOption({label:'Rainwater harvesting'});
 await page.getByLabel('Completion date').fill('2026-09-30');
 await page.getByLabel('Location (self-reported)').fill('Kabrai');
 await page.getByLabel('What work was completed?').fill('Rainwater collection tank installed.');
 await page.locator('input[type=file]').setInputFiles({name:'receipt.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\nDemo receipt')});
 await page.getByRole('button',{name:'Submit for review',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('Evidence submitted');
 await page.getByLabel('Demo role').selectOption('Field verifier');
 const row=page.getByRole('row').filter({hasText:'Rainwater harvesting'});
 await row.getByRole('button',{name:'Review',exact:true}).click();
 await page.getByLabel('Reviewer notes').fill('Please clarify the tank capacity.');
 await page.getByRole('button',{name:'Request changes',exact:true}).click();
 await page.getByLabel('Demo role').selectOption('Farmer');
 await expect(page.locator('.next')).toContainText('Update your evidence');
 await page.getByRole('button',{name:'Submit evidence',exact:true}).click();
 await page.getByLabel('Improvement',{exact:true}).selectOption({label:'Rainwater harvesting'});
 await page.getByLabel('What work was completed?').fill('A 1000 litre rainwater collection tank installed.');
 await page.getByRole('button',{name:'Resubmit for review'}).click();
 await page.getByLabel('Demo role').selectOption('Field verifier');
 await row.getByRole('button',{name:'Review',exact:true}).click();
 await page.getByRole('button',{name:'Start review',exact:true}).click();
 for(const check of ['Farm and improvement details checked','Evidence reviewed using the selected method','Completion and outstanding issues recorded'])await page.getByLabel(check).check();
 await page.getByLabel('Reviewer notes').fill('Tank capacity checked during demo field visit.');
 await page.getByRole('button',{name:'Mark verified',exact:true}).click();
 await expect(row).toContainText('Verified');
 await page.getByLabel('Demo role').selectOption('Farmer');
 await page.getByRole('button',{name:'Dhara passport',exact:true}).click();
 await page.getByRole('button',{name:'Share with demo lender',exact:true}).click();
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Confirm sharing'}).click();
 await page.getByLabel('Demo role').selectOption('Lender');
 await page.getByRole('row').filter({hasText:'Sunita Devi'}).getByRole('button',{name:'Open',exact:true}).click();
 await page.getByRole('button',{name:'Start review',exact:true}).click();
 await page.getByRole('button',{name:'Request information'}).click();
 await page.getByLabel('What do you need from Sunita Devi?').fill('Please confirm the crop for next season.');
 await page.getByRole('button',{name:'Send information request'}).click();
 await page.getByLabel('Demo role').selectOption('Farmer');
 await page.getByRole('button',{name:'Respond',exact:true}).click();
 await page.getByLabel('Your response (self-reported)').fill('Wheat and pulses for the next season.');
 await page.getByRole('button',{name:'Send response'}).click();
 await page.getByLabel('Demo role').selectOption('Lender');
 await page.getByRole('row').filter({hasText:'Sunita Devi'}).getByRole('button',{name:'Open',exact:true}).click();
 await expect(page.locator('.passport')).toContainText('Wheat and pulses for the next season.');
 await page.getByRole('button',{name:'Mark review complete'}).click();
 await page.reload();
 await page.getByLabel('Demo role').selectOption('Lender');
 await expect(page.getByRole('row').filter({hasText:'Sunita Devi'})).toContainText('Review complete');
 await page.getByLabel('Demo role').selectOption('Farmer');
 await page.getByRole('button',{name:'Dhara passport',exact:true}).click();
 await page.getByRole('button',{name:'Revoke sharing'}).click();
 await page.getByRole('button',{name:'Revoke access'}).click();
 await page.getByLabel('Demo role').selectOption('Lender');
 await expect(page.getByRole('row').filter({hasText:'Sunita Devi'})).toHaveCount(0);
});
